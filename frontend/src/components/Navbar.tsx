import { useState, useRef, useEffect } from 'react';
import { Link, useLocation } from 'react-router-dom';

interface DropdownItem {
  to: string;
  label: string;
  icon: React.ReactNode;
}

function Dropdown({
  label,
  icon,
  items,
  matchPaths,
}: {
  label: string;
  icon: React.ReactNode;
  items: DropdownItem[];
  matchPaths: string[];
}) {
  const location = useLocation();
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  const isActive = matchPaths.some((p) => location.pathname.startsWith(p));

  useEffect(() => {
    function handleClick(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    document.addEventListener('mousedown', handleClick);
    return () => document.removeEventListener('mousedown', handleClick);
  }, []);

  return (
    <div className="relative" ref={ref}>
      <button
        onClick={() => setOpen((o) => !o)}
        className={`px-3 py-1 rounded transition flex items-center gap-1.5 ${
          isActive
            ? 'bg-white text-indigo-700 font-semibold'
            : 'hover:bg-indigo-600'
        }`}
      >
        {icon}
        {label}
        <svg
          className={`w-3 h-3 ml-0.5 transition-transform ${open ? 'rotate-180' : ''}`}
          fill="none"
          viewBox="0 0 24 24"
          stroke="currentColor"
          strokeWidth={2.5}
        >
          <path strokeLinecap="round" strokeLinejoin="round" d="M19 9l-7 7-7-7" />
        </svg>
      </button>

      {open && (
        <div className="absolute right-0 mt-1 w-44 bg-white rounded-lg shadow-lg ring-1 ring-black/5 z-50 py-1">
          {items.map((item) => (
            <Link
              key={item.to}
              to={item.to}
              onClick={() => setOpen(false)}
              className={`flex items-center gap-2.5 px-3 py-2 text-sm transition ${
                location.pathname.startsWith(item.to)
                  ? 'bg-indigo-50 text-indigo-700 font-semibold'
                  : 'text-gray-700 hover:bg-gray-50'
              }`}
            >
              <span className="text-gray-400">{item.icon}</span>
              {item.label}
            </Link>
          ))}
        </div>
      )}
    </div>
  );
}

function NavLink({ to, label, icon }: { to: string; label: string; icon?: React.ReactNode }) {
  const location = useLocation();
  const active = location.pathname.startsWith(to);
  return (
    <Link
      to={to}
      className={`px-3 py-1 rounded transition flex items-center gap-1.5 ${
        active ? 'bg-white text-indigo-700 font-semibold' : 'hover:bg-indigo-600'
      }`}
    >
      {icon}
      {label}
    </Link>
  );
}

